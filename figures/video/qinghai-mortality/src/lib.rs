//! Video abstract v2 (house style, FIGURE_DESIGN §8): Qinghai Lake 2005
//! mortality discrepancy. Beats: hook (title) -> tension (two estimates,
//! count-up, divergence badge) -> resolution (explanations) -> outro.
use fframes::{
    AudioMap, Color, Duration, FFramesContext, Frame, Svgr, Transform, Video,
    animation::Easing, include_media_dir,
};

include_media_dir!(pub struct QinghaiMedia, "media");

pub const WIDTH: usize = 1920;
pub const HEIGHT: usize = 1080;
const UNIT: f32 = HEIGHT as f32 / 1080.0;

const FONT: &str = "DM Sans";
const WEIGHT: u16 = 500;
const BOLD: u16 = 700;
const INK: &str = "#0f172a";
const MUTED: &str = "#475569";
const FAINT: &str = "#94a3b8";
const BLUE: &str = "#1d4ed8";
const BLUE_BG: &str = "#eff6ff";
const RED: &str = "#dc2626";

pub struct QinghaiVideo<'a> {
    pub media: &'a QinghaiMedia,
}

impl std::fmt::Debug for QinghaiVideo<'_> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("QinghaiVideo").finish()
    }
}

fn fmt(n: u32) -> String {
    let s = n.to_string();
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if i > 0 && (s.len() - i) % 3 == 0 {
            out.push(',');
        }
        out.push(c);
    }
    out
}

impl Video for QinghaiVideo<'_> {
    const FPS: usize = 30;
    const WIDTH: usize = WIDTH;
    const HEIGHT: usize = HEIGHT;
    const BACKGROUND_COLOR: Color = Color::WHITE;

    fn duration(&self) -> Duration<'_> {
        Duration::Seconds(14.0)
    }

    fn audio(&self) -> AudioMap<'_> {
        // ambient bed generated by the Roost figure system (CC0-by-construction)
        use fframes::{AudioTrack, AudioTimestamp::*};
        AudioMap::from([
            AudioTrack::new("ambient-pad.wav", Second(0.)..Eof).gain_db(-16.).fade_in(1.2).fade_out(1.5),
        ])
    }

    fn render_frame<'a>(&'a self, mut frame: Frame, ctx: &FFramesContext<'a, '_>) -> Svgr<'a> {
        let _ = &ctx;
        let t = frame.seconds() as f32;
        let spring = Easing::Spring { mass: 1.0, stiffness: 170.0, damping: 21.0 };

        // hook
        let rise = frame.animate(&fframes::timeline!(at 0.2, animate 46.0_f32 => 0.0, spring));
        // tension: cards slide from opposite sides, counters run
        let card_l = frame.animate(&fframes::timeline!(at 1.7, animate -520.0_f32 => 0.0, spring));
        let card_r = frame.animate(&fframes::timeline!(at 2.0, animate 520.0_f32 => 0.0, spring));
        let e1 = frame.animate(&fframes::timeline!(at 2.3 => 3.9, animate 0.0_f32 => 1.0, Easing::EaseOut));
        let e2 = frame.animate(&fframes::timeline!(at 2.7 => 4.3, animate 0.0_f32 => 1.0, Easing::EaseOut));
        let badge = frame.animate(&fframes::timeline!(at 4.4, animate 0.0_f32 => 1.0, spring));
        let pulse = 0.9 + 0.1 * (t * 2.4).sin();
        // resolution + outro
        let expl = frame.animate(&fframes::timeline!(at 7.2 => 7.9, animate 0.0_f32 => 1.0, Easing::EaseOut));
        let fade_out = frame.animate(&fframes::timeline!(at 13.1 => 13.8, animate 1.0_f32 => 0.0, Easing::EaseIn));

        let low = (1500.0 * e1).round() as u32;
        let high = (6194.0 * e2).round() as u32;
        let cx = WIDTH as f32 / 2.0;
        let fade = |from: f32, dur: f32| if t < from { 0.0 } else { ((t - from) / dur).min(1.0) };

        fframes::svgr!(
            <svg xmlns="http://www.w3.org/2000/svg" viewBox={format!("0 0 {WIDTH} {HEIGHT}")} width={WIDTH} height={HEIGHT}>
                <rect width={WIDTH} height={HEIGHT} fill="#f8fafc" />

                <g opacity={fade(0.15, 0.6) * fade_out} transform={Transform::translate(0, rise * UNIT)}>
                    <text x={cx} y={128. * UNIT} font-family={FONT} font-size={26. * UNIT} font-weight={WEIGHT} fill={MUTED} text-anchor="middle" letter-spacing="7">
                        "RESEARCH BRIEFING · VIDEO ABSTRACT"
                    </text>
                    <text x={cx} y={205. * UNIT} font-family={FONT} font-size={72. * UNIT} font-weight={BOLD} fill={INK} text-anchor="middle">
                        "Same event. Two magnitudes."
                    </text>
                </g>

                <g opacity={fade(1.7, 0.45) * fade_out} transform={Transform::translate(card_l * UNIT, 0)}>
                    <rect x={170. * UNIT} y={290. * UNIT} width={640. * UNIT} height={330. * UNIT} rx={26. * UNIT} fill="#ffffff" stroke="#cbd5e1" stroke-width={3. * UNIT} />
                    <text x={230. * UNIT} y={362. * UNIT} font-family={FONT} font-size={28. * UNIT} font-weight={WEIGHT} fill={MUTED}>"Beatriz et al. 2025"</text>
                    <text x={230. * UNIT} y={505. * UNIT} font-family={FONT} font-size={130. * UNIT} font-weight={BOLD} fill={MUTED}>
                        {fmt(low)}
                    </text>
                    <text x={230. * UNIT} y={572. * UNIT} font-family={FONT} font-size={24. * UNIT} font-weight={WEIGHT} fill={FAINT} font-style="italic">"“death of 1,500 birds”"</text>
                </g>

                <g opacity={fade(2.0, 0.45) * fade_out} transform={Transform::translate(card_r * UNIT, 0)}>
                    <rect x={1110. * UNIT} y={290. * UNIT} width={640. * UNIT} height={330. * UNIT} rx={26. * UNIT} fill={BLUE_BG} stroke={BLUE} stroke-width={5. * UNIT} />
                    <text x={1170. * UNIT} y={362. * UNIT} font-family={FONT} font-size={28. * UNIT} font-weight={WEIGHT} fill={BLUE}>"Alejandro et al. 2025"</text>
                    <text x={1170. * UNIT} y={505. * UNIT} font-family={FONT} font-size={130. * UNIT} font-weight={BOLD} fill={BLUE}>
                        {if e2 >= 1.0 { format!(">{}", fmt(high)) } else { fmt(high) }}
                    </text>
                    <text x={1170. * UNIT} y={572. * UNIT} font-family={FONT} font-size={24. * UNIT} font-weight={WEIGHT} fill={MUTED} font-style="italic">"waterfowl · 4 May – 29 Jun 2005"</text>
                </g>

                <g opacity={badge}>
                    <rect x={cx - 150. * UNIT} y={396. * UNIT} width={300. * UNIT} height={118. * UNIT} rx={59. * UNIT} fill={RED} transform={format!("scale({}) translate({} {})", pulse, cx - cx * pulse, 455. * UNIT * (1.0 - pulse))} />
                    <text x={cx} y={450. * UNIT} font-family={FONT} font-size={56. * UNIT} font-weight={BOLD} fill="#ffffff" text-anchor="middle">"≈ 4.1×"</text>
                    <text x={cx} y={492. * UNIT} font-family={FONT} font-size={22. * UNIT} font-weight={WEIGHT} fill="#fecaca" text-anchor="middle">"divergence"</text>
                </g>

                <g opacity={expl * fade_out}>
                    <text x={cx} y={702. * UNIT} font-family={FONT} font-size={40. * UNIT} font-weight={BOLD} fill="#b45309" text-anchor="middle">
                        "Why do two syntheses disagree?"
                    </text>
                    <text x={cx} y={756. * UNIT} font-family={FONT} font-size={28. * UNIT} font-weight={WEIGHT} fill={MUTED} text-anchor="middle">
                        "temporal scope · taxonomic scope · surveillance intensity · mortality definitions"
                    </text>
                </g>

                <g opacity={fade(11.0, 0.6) * fade_out}>
                    <text x={cx} y={866. * UNIT} font-family={FONT} font-size={34. * UNIT} font-weight={BOLD} fill={INK} text-anchor="middle">
                        "The canonical spillover origin story rests on a number nobody agrees on."
                    </text>
                </g>

                <text x={52. * UNIT} y={HEIGHT as f32 - 44. * UNIT} font-family={FONT} font-size={21. * UNIT} font-weight={WEIGHT} fill={FAINT}>
                    "Roost · briefing: Qinghai-Lake-mortality-discrep-contradiction-investigati"
                </text>
            </svg>
        )
    }
}
