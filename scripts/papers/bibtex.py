#!/usr/bin/env python3
"""
BibTeX export (D72): generate .bib entries for all papers.

Output: data/papers/roost.bib (all) — one entry per paper, keyed by paper id.
Types: @article (with journal), @phdthesis, @techreport, @incollection,
@misc fallback. Uses authors_list (structured) when present.

Usage: pixi run python scripts/papers/bibtex.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).parent.parent.parent
PAPERS_JSON = ROOT / "web" / "public" / "data" / "papers.json"
OUT = ROOT / "data" / "papers" / "roost.bib"

DOC_TYPE_MAP = {
    "article": "article",
    "review": "article",
    "preprint": "misc",
    "thesis": "phdthesis",
    "report": "techreport",
    "book-chapter": "incollection",
    "news": "misc",
}


def tex_escape(s):
    return (s or "").replace("\\", "\\textbackslash{}").replace("&", "\\&") \
        .replace("%", "\\%").replace("$", "\\$").replace("#", "\\#") \
        .replace("_", "\\_").replace("{", "\\{").replace("}", "\\}") \
        .replace("~", "\\textasciitilde{}").replace("^", "\\textasciicircum{}")


def bibtex_authors(p):
    """'Family, Given and Family, Given and ...' — full list."""
    if p.get("authors_list"):
        names = []
        for a in p["authors_list"]:
            fam = (a.get("family") or "").strip()
            giv = (a.get("given") or "").strip()
            if fam:
                names.append(f"{tex_escape(fam)}, {tex_escape(giv)}" if giv else tex_escape(fam))
        if names:
            return " and ".join(names)
    # fall back to the display string
    return tex_escape((p.get("authors") or "").replace(", et al.", " and others"))


def entry_for(p):
    pid = re.sub(r"[^A-Za-z0-9_]", "", p["id"])
    dt = DOC_TYPE_MAP.get(p.get("doc_type") or "", "misc")
    fields = []

    authors = bibtex_authors(p)
    if authors:
        fields.append(f"  author = {{{authors}}}")
    if p.get("title"):
        fields.append(f"  title = {{{tex_escape(p['title'])}}}")

    if dt == "article":
        if p.get("journal"):
            fields.append(f"  journal = {{{tex_escape(p['journal'])}}}")
    elif dt == "phdthesis":
        fields.append("  school = {Unknown institution}")
    elif dt == "techreport":
        fields.append(f"  institution = {{{tex_escape(p.get('source') or 'Unknown')}}}")
    elif dt == "incollection":
        fields.append("  booktitle = {Avian Immunology}")

    if p.get("year"):
        fields.append(f"  year = {{{p['year']}}}")
    if p.get("doi"):
        fields.append(f"  doi = {{{p['doi']}}}")
    if p.get("url"):
        fields.append(f"  url = {{{p['url']}}}")
    if p.get("doc_type") == "preprint":
        fields.append("  note = {Preprint}")
    if p.get("title_original"):
        fields.append(f"  originaltitle = {{{tex_escape(p['title_original'])}}}")

    fields.append(f"  keywords = {{{tex_escape(', '.join(p.get('topics', [])[:6]))}}}")

    return f"@{dt}{{{pid},\n" + ",\n".join(fields) + "\n}"


def main():
    papers = json.loads(PAPERS_JSON.read_text())["papers"]
    entries = [entry_for(p) for p in papers]
    header = (
        f"% Roost — avian influenza host genomics resource\n"
        f"% {len(papers)} papers, generated by scripts/papers/bibtex.py\n"
        f"% Primary data sources should also be cited — see /#/credits\n\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + "\n\n".join(entries) + "\n")
    print(f"wrote {len(entries)} entries → {OUT}")

    # stats
    with_journal = sum(1 for p in papers if p.get("journal"))
    with_year = sum(1 for p in papers if p.get("year"))
    with_doi = sum(1 for p in papers if p.get("doi"))
    print(f"  journal: {with_journal}, year: {with_year}, doi: {with_doi}")


if __name__ == "__main__":
    main()
