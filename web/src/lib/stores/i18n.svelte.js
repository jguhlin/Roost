/** Paper field translation: pt(paperId, 'title'|'summary'|'cited_for') → translated or null */
export function pt(paperId, field = 'summary') {
  if (state.locale === 'en') return null;
  return state.papers[state.locale]?.papers?.[paperId]?.[field] || null;
}

/** Topic/category vocabulary: ptopic('Ducks') → '鸭类' or original */
export function ptopic(topic) {
  if (state.locale === 'en' || !topic) return topic;
  return state.papers[state.locale]?.topics?.[topic] || topic;
}

/** Finding/role/conclusion translation by content-hash key (fh field) */
export function ft(hash) {
  if (state.locale === 'en' || !hash) return null;
  const p = state.papers[state.locale];
  if (!p) return null;
  return p.findings?.[hash] || p.conclusions?.[hash] || p.roles?.[hash] || null;
}

/** Reviewed-evidence quote translation by content-hash key (quote_h field) */
export function et(hash) {
  if (state.locale === 'en' || !hash) return null;
  return state.papers[state.locale]?.evidence?.[hash] || null;
}

/** Vocabulary translation (mechanism labels, species, evidence types, stage
 *  labels — the text AROUND verbatim quotes). Falls back to the input. */
export function vt(text) {
  if (state.locale === 'en' || !text) return text;
  return state.papers[state.locale]?.vocab?.[text] || text;
}

/** Gene-profile text translation by content-hash (D92).
 *  Profiles store an `_h` suffix field with the hash of the English text. */
export function gpt(text, hash) {
  if (state.locale === 'en' || !text) return text;
  if (hash) {
    const t = state.papers[state.locale]?.profiles?.[hash];
    if (t) return t;
  }
  return text;
}

