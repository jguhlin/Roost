// Load English fallbacks from extraction (prevents raw key leakage)
// Bust cache in dev: i18n JSON updates must be picked up on reload
const i18nV = import.meta.env?.DEV ? '?v=' + Date.now() : '';
if (typeof fetch !== 'undefined') {
  Promise.all([
    fetch('data/i18n/extraction.json' + i18nV, { cache: 'reload' }).then(r => r.ok ? r.json() : {}).catch(() => ({})),
    fetch('data/i18n/final_extract.json' + i18nV, { cache: 'reload' }).then(r => r.ok ? r.json() : {}).catch(() => ({})),
    fetch('data/i18n/en_i18n.json' + i18nV, { cache: 'reload' }).then(r => r.ok ? r.json() : {}).catch(() => ({})),
  ]).then(([extraction, final, enFile]) => {
      for (const [key, val] of Object.entries(extraction)) {
        if (val && val.english) {
          state.fallbacks[key] = val.english;
        }
      }
      for (const [key, val] of Object.entries(final)) {
        if (typeof val === 'string') {
          state.fallbacks[key] = val;
        }
      }
      // en_i18n.json (gap-fill output) is the last-resort English source —
      // fills keys that extraction/final never captured
      for (const [key, val] of Object.entries(enFile)) {
        if (typeof val === 'string' && !state.fallbacks[key]) {
          state.fallbacks[key] = val;
        }
      }
    })
    .catch(() => {});
}

// Initialize from localStorage
if (typeof localStorage !== 'undefined') {
  const saved = localStorage.getItem(LOCALE_KEY);
  if (saved && SUPPORTED.includes(saved)) {
    state.locale = saved;
  }
}

// Load translations for a locale
async function loadLocale(lang) {
  if (lang === 'en') return;
  const loadPapers = !state.papers[lang];
  if (!state.translations[lang] || loadPapers) {
    try {
      const fetches = [
        fetch(`data/i18n/${lang}_i18n.json${i18nV}`, { cache: 'reload' }).then(r => r.ok ? r.json() : {}).catch(() => ({})),
        fetch(`data/i18n/${lang}.json${i18nV}`, { cache: 'reload' }).then(r => r.ok ? r.json() : {}).catch(() => ({})),
        fetch(`data/i18n/${lang}_content.json${i18nV}`, { cache: 'reload' }).then(r => r.ok ? r.json() : {}).catch(() => ({})),
      ];
      if (loadPapers) {
        fetches.push(
          fetch(`data/i18n/papers/${lang}.json${i18nV}`, { cache: 'reload' })
            .then(r => r.ok ? r.json() : {}).catch(() => ({})));
      }
      const [r1, r2, r3, r4] = await Promise.all(fetches);
      state.translations[lang] = { ...r1, ...r2, ...(state.translations[lang] || {}) };
      state.rev++;
      state.content[lang] = { ...r2, ...r3 };  // content keys available via tc()
      if (loadPapers && r4) state.papers[lang] = r4;
    } catch {
      // fallback to English
    }
  }
}

// Load initial locale if not English
if (state.locale !== 'en') {
  loadLocale(state.locale);
}

export function t(key, params) {
  let s = state.translations[state.locale]?.[key] || en[key] || state.fallbacks[key] || key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split('{' + k + '}').join(String(v));
  return s;
}

// Translate content keys (model descriptions, methods text, etc.)
// Returns undefined if no translation — caller falls back to English
export function tc(key) {
  const content = state.content[state.locale] || {};
  return content[key] || undefined;
}

